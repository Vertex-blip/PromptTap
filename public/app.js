function node(tag, className, text) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (text !== undefined) element.textContent = text;
  return element;
}

function toast(message) {
  clearTimeout(toastTimer);
  $('#toast').textContent = message;
  $('#toast').hidden = false;
  toastTimer = setTimeout(() => { $('#toast').hidden = true; }, 3500);
}

function persist(key, value) {
  try { localStorage.setItem(key, JSON.stringify(value)); return true; }
  catch { toast(t('storageError')); return false; }
}

function showStatus(target, key, loading = false) {
  const container = $(target);
  container.replaceChildren();
  if (!key) return;
  const content = node('div', loading ? 'loading' : 'empty-state');
  if (loading) content.append(node('span', 'spinner'));
  content.append(node('span', '', t(key)));
  container.append(content);
}

async function request(path, options = {}, raw = false) {
  const headers = new Headers(options.headers);
  if (options.body) headers.set('Content-Type', 'application/json');
  const initData = window.Telegram?.WebApp?.initData;
  if (initData) headers.set('X-Telegram-Init-Data', initData);
  let response;
  try { response = await fetch(`${apiBaseUrl}${path}`, { ...options, headers, signal: options.signal || AbortSignal.timeout(65000) }); }
  catch (error) {
    if (error.name === 'AbortError') throw error;
    throw new Error(t('networkError'));
  }
  if (!response.ok) {
    if (response.status === 401 || response.status === 403) {
      state.requiresTelegram = true;
      renderTelegramEntry();
      const error = new Error(t('telegramEntry'));
      error.code = 'TELEGRAM_REQUIRED';
      throw error;
    }
    if (response.status === 422) {
      const body = await response.json().catch(() => ({}));
      if (typeof body.error === 'string') throw new Error(body.error);
    }
    const errorKey = response.status === 401 || response.status === 403 ? 'authError' : response.status === 429 ? 'rateError' : response.status === 400 ? 'validationError' : 'requestError';
    throw new Error(t(errorKey));
  }
  return raw ? response : response.json();
}

function renderTelegramEntry() {
  const required = state.requiresTelegram;
  $('#telegram-entry').hidden = !required;
  $('#search-form').hidden = required;
  $('.category-section').hidden = required;
  $('#suggestions').hidden = required || Boolean(state.query);
  $('#telegram-open').href = botUrl.href;
  if (required) {
    $('#results-section').hidden = true;
    $('#saved-page').hidden = true;
    $('#search-page').hidden = false;
    $('#prompt-dialog').close();
  }
}

function openTelegram() {
  if (window.Telegram?.WebApp?.openTelegramLink) {
    window.Telegram.WebApp.openTelegramLink(botUrl.href);
  } else {
    window.location.assign(botUrl.href);
  }
}

function renderCategories() {
  const categories = ['all', ...(state.meta?.categories || []).map(category => category.id)];
  const uniqueCategories = [...new Set(categories.length > 1 ? categories : ['all','design','code','writing','marketing','study','productivity'])];
  $('#category-filters').replaceChildren(...uniqueCategories.map(category => {
    const button = node('button', `category-chip${state.category === category ? ' active' : ''}`, categoryName(category));
    button.type = 'button';
    button.setAttribute('aria-pressed', String(state.category === category));
    button.addEventListener('click', () => {
      state.category = category;
      renderCategories();
      if ($('#query').value.trim()) search();
      else $('#query').focus();
    });
    return button;
  }));
}

